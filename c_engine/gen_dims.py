"""Emit the C dimension header from the trained model configuration.

The edge runtime, the ctypes binding and the trained weights must agree on
D/H/R/C. They had drifted to D=58 in C against D=24 in the model, so the
runtime could not consume the model at all. Generating the header removes the
opportunity for drift.
"""

import json
from pathlib import Path

C_DIR = Path(__file__).resolve().parent
ROOT = C_DIR.parent
DOCS_DIR = ROOT / "docs" if (ROOT / "docs" / "config.json").exists() else ROOT / "Fault-Prediction-in-Vehicles" / "docs"
CONFIG_PATH = DOCS_DIR / "config.json"
MODEL_PATH = DOCS_DIR / "model.json"
DIMS_HEADER = C_DIR / "tank_pdm_dims.h"


def model_dims() -> dict:
    """Authoritative D/H/R/C, read from the exported model artifacts."""
    cfg = json.loads(CONFIG_PATH.read_text(encoding="utf-8"))
    model = json.loads(MODEL_PATH.read_text(encoding="utf-8"))
    dims = {
        "D": len(cfg["input_features"]),
        "H": int(model["H"]),
        "R": len(cfg["part_order"]),
        "C": len(cfg["class_names"]),
    }
    if dims["D"] != int(model["D"]):
        raise ValueError(
            f"config declares {dims['D']} input features but model.json has "
            f"D={model['D']}; retrain or re-export before generating dims")
    if dims["R"] != int(model["R"]) or dims["C"] != int(model["C"]):
        raise ValueError(
            f"config/model disagree on R or C: config R={dims['R']} C={dims['C']}, "
            f"model R={model['R']} C={model['C']}")
    return dims


def write_dims_header(path: Path = DIMS_HEADER) -> Path:
    d = model_dims()
    path.write_text(
        "/* GENERATED by c_engine/gen_dims.py -- do not edit.\n"
        "   Regenerate with: python -m c_engine.gen_dims */\n"
        "#ifndef TANK_PDM_DIMS_H\n"
        "#define TANK_PDM_DIMS_H\n\n"
        f"#define TANK_INFER_D_FEATURES   {d['D']}\n"
        f"#define TANK_INFER_H_HIDDEN     {d['H']}\n"
        f"#define TANK_INFER_R_PARTS      {d['R']}\n"
        f"#define TANK_INFER_C_CLASSES    {d['C']}\n\n"
        "#endif /* TANK_PDM_DIMS_H */\n",
        encoding="utf-8")
    return path


if __name__ == "__main__":
    print(f"wrote {write_dims_header()} from {CONFIG_PATH.name}: {model_dims()}")
